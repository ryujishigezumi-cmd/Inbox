"""業種区分。実データは文部科学省「学校基本調査」の産業分類を粗くまとめた標準区分に揃える。

大学ごとに公開区分が異なるため、取り込み時に下表で標準区分へ寄せる（細かい区分は合算）。
"""

STANDARD_INDUSTRIES = [
    "農林漁業・鉱業", "建設業", "製造業", "電気・ガス・熱供給・水道業", "情報通信業", "運輸業・郵便業",
    "卸売業・小売業", "金融業・保険業", "不動産業・物品賃貸業", "サービス業", "公務", "その他",
]

# 大学の公開区分 → 標準区分（部分一致。上から順に判定するので、紛らわしい語を含む区分を先に置く）
_RULES = [
    (("農", "林業", "漁業", "鉱業", "水産"), "農林漁業・鉱業"),
    (("社会福祉", "社会保険・", "介護"), "サービス業"),  # 「保険」を含むが医療・福祉
    (("私立学校",), "サービス業"),                     # 教員だが公務ではない（教育・学習支援業）
    (("卸売", "小売", "卸・", "商社", "貿易"), "卸売業・小売業"),  # 「食品卸売業」等を製造業にしない
    (("建設",), "建設業"),
    (("製造", "メーカー", "食品", "印刷", "工業", "鉄鋼"), "製造業"),
    (("電気", "ガス", "水道", "熱供給", "エネルギー", "インフラ"), "電気・ガス・熱供給・水道業"),
    (("運輸", "郵便", "物流", "航空"), "運輸業・郵便業"),
    (("情報通信", "通信", "情報サービス", "ソフトウェア", "インターネット", "映像", "情報制作",
      "IT", "マスコミ", "放送", "新聞", "出版"), "情報通信業"),
    (("金融", "保険", "銀行", "証券", "金庫", "信用組合", "貸金", "クレジット", "商品取引"), "金融業・保険業"),
    (("不動産", "物品賃貸", "リース"), "不動産業・物品賃貸業"),
    (("公務", "官公庁", "教員"), "公務"),
    (("サービス", "教育", "学術", "学習", "医療", "福祉", "保健", "宿泊", "飲食", "広告", "メディア", "専門・技術",
      "コンサル", "学校", "幼稚園", "保育", "こども園", "施設", "旅行", "観光", "娯楽", "法律", "法務", "宗教",
      "団体"), "サービス業"),
]
_EXACT = {"情報": "情報通信業"}


def standardize_industry(label: str) -> str:
    if not label:
        return "その他"
    label = label.strip()
    if label in STANDARD_INDUSTRIES:
        return label
    if label in _EXACT:
        return _EXACT[label]
    for words, std in _RULES:
        if any(w in label for w in words):
            return std
    return "その他"
