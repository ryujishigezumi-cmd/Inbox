"""業種区分。実データは文部科学省「学校基本調査」の産業分類を粗くまとめた標準区分に揃える。

大学ごとに公開区分が異なるため、取り込み時に下表で標準区分へ寄せる（細かい区分は合算）。
"""

STANDARD_INDUSTRIES = [
    "農林漁業・鉱業", "建設業", "製造業", "電気・ガス・熱供給・水道業", "情報通信業", "運輸業・郵便業",
    "卸売業・小売業", "金融業・保険業", "不動産業・物品賃貸業", "サービス業", "公務", "その他",
]

# 大学の公開区分 → 標準区分（部分一致。上から順に判定）
_RULES = [
    (("農", "林業", "漁業", "鉱業"), "農林漁業・鉱業"),
    (("建設",), "建設業"),
    (("製造", "メーカー", "食品"), "製造業"),
    (("電気", "ガス", "水道", "熱供給", "インフラ"), "電気・ガス・熱供給・水道業"),
    (("情報通信", "通信", "情報サービス", "ソフトウェア", "IT"), "情報通信業"),
    (("運輸", "郵便", "物流", "航空", "旅行"), "運輸業・郵便業"),
    (("卸売", "小売", "商社"), "卸売業・小売業"),
    (("金融", "保険", "銀行", "証券"), "金融業・保険業"),
    (("不動産", "物品賃貸"), "不動産業・物品賃貸業"),
    (("公務", "教員"), "公務"),
    (("サービス", "教育", "学術", "医療", "福祉", "宿泊", "飲食", "広告", "メディア", "専門・技術", "コンサル"), "サービス業"),
]


def standardize_industry(label: str) -> str:
    if not label:
        return "その他"
    label = label.strip()
    if label in STANDARD_INDUSTRIES:
        return label
    for words, std in _RULES:
        if any(w in label for w in words):
            return std
    return "その他"
